"""Generates the CycleScope app icon from a single geometry definition.

Outputs:
  - assets/branding/app_icon.svg            master artwork (full bleed square)
  - assets/branding/app_icon_512.png        store / README icon
  - android/.../drawable/ic_launcher_background.xml   adaptive background
  - android/.../drawable/ic_launcher_foreground.xml   adaptive foreground
  - android/.../drawable/ic_launcher_monochrome.xml   themed icon (Android 13+)
  - android/.../mipmap-anydpi-v26/ic_launcher.xml     adaptive icon
  - android/.../mipmap-*/ic_launcher.png              legacy raster icons

Motif: a stopwatch whose rim is a cycle arrow, with three coloured work
steps on the dial. All coordinates live on the 108 x 108 adaptive icon
canvas; the important parts stay inside the 66 unit safe zone.

Run from the repository root:  python tool/generate_app_icon.py
Requires Pillow.
"""

import math
import os

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")
BRANDING = os.path.join(ROOT, "assets", "branding")

CANVAS = 108.0
CX, CY = 54.0, 56.5

BG_TOP = "#127F9F"
BG_BOTTOM = "#07465C"
WHITE = "#FFFFFF"

RING_R = 22.5
RING_W = 4.6
RING_START, RING_END = 22.0, 318.0  # degrees, clockwise from 12 o'clock

ARROW_LEN = 7.5
ARROW_HALF_W = 5.6

CROWN = (48.5, 25.5, 59.5, 30.5)  # left, top, right, bottom
CROWN_RADIUS = 1.6
STEM = (52.3, 30.0, 55.7, 34.8)

STEP_R = 13.5
STEP_W = 6.5
STEP_GAP = 9.0
STEPS = [  # (start, end, colour) of the work steps on the dial
    (0.0, 150.0, "#4FC3F7"),
    (150.0, 245.0, "#81C784"),
    (245.0, 360.0, "#FFB74D"),
]

HAND_ANGLE = 48.0
HAND_LEN = 15.5
HAND_W = 3.2
HUB_R = 3.6


def point(angle, radius):
    a = math.radians(angle)
    return CX + radius * math.sin(a), CY - radius * math.cos(a)


def fmt(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def arc_path(start, end, radius):
    x1, y1 = point(start, radius)
    x2, y2 = point(end, radius)
    large = 1 if (end - start) % 360 > 180 else 0
    r = fmt(radius)
    return f"M{fmt(x1)},{fmt(y1)} A{r},{r} 0 {large} 1 {fmt(x2)},{fmt(y2)}"


def arrow_points():
    tip_angle = RING_END
    base = point(tip_angle, RING_R)
    # Tangent for clockwise travel at the arc end.
    a = math.radians(tip_angle)
    tx, ty = math.cos(a), math.sin(a)
    nx, ny = math.sin(a), -math.cos(a)  # outward normal
    tip = (base[0] + tx * ARROW_LEN, base[1] + ty * ARROW_LEN)
    left = (base[0] + nx * ARROW_HALF_W, base[1] + ny * ARROW_HALF_W)
    right = (base[0] - nx * ARROW_HALF_W, base[1] - ny * ARROW_HALF_W)
    return [tip, left, right]


def poly_path(points):
    head, *rest = points
    body = " ".join(f"L{fmt(x)},{fmt(y)}" for x, y in rest)
    return f"M{fmt(head[0])},{fmt(head[1])} {body} Z"


def round_rect_path(rect, r):
    l, t, rt, b = rect
    return (
        f"M{fmt(l + r)},{fmt(t)} L{fmt(rt - r)},{fmt(t)} "
        f"A{fmt(r)},{fmt(r)} 0 0 1 {fmt(rt)},{fmt(t + r)} "
        f"L{fmt(rt)},{fmt(b - r)} "
        f"A{fmt(r)},{fmt(r)} 0 0 1 {fmt(rt - r)},{fmt(b)} "
        f"L{fmt(l + r)},{fmt(b)} "
        f"A{fmt(r)},{fmt(r)} 0 0 1 {fmt(l)},{fmt(b - r)} "
        f"L{fmt(l)},{fmt(t + r)} "
        f"A{fmt(r)},{fmt(r)} 0 0 1 {fmt(l + r)},{fmt(t)} Z"
    )


def rect_path(rect):
    l, t, r, b = rect
    return poly_path([(l, t), (r, t), (r, b), (l, b)])


def circle_path(cx, cy, r):
    return (
        f"M{fmt(cx - r)},{fmt(cy)} "
        f"A{fmt(r)},{fmt(r)} 0 1 1 {fmt(cx + r)},{fmt(cy)} "
        f"A{fmt(r)},{fmt(r)} 0 1 1 {fmt(cx - r)},{fmt(cy)} Z"
    )


def step_arcs():
    half = STEP_GAP / 2
    return [(s + half, e - half, c) for s, e, c in STEPS]


def hand_end():
    return point(HAND_ANGLE, HAND_LEN)


# Shapes: ("stroke", path, colour, width) or ("fill", path, colour)
def shapes(monochrome=False):
    items = [
        ("stroke", arc_path(RING_START, RING_END, RING_R), WHITE, RING_W),
        ("fill", poly_path(arrow_points()), WHITE),
        ("fill", round_rect_path(CROWN, CROWN_RADIUS), WHITE),
        ("fill", rect_path(STEM), WHITE),
    ]
    for s, e, c in step_arcs():
        items.append(("stroke", arc_path(s, e, STEP_R), WHITE if monochrome else c, STEP_W))
    hx, hy = hand_end()
    items.append(
        ("stroke", f"M{fmt(CX)},{fmt(CY)} L{fmt(hx)},{fmt(hy)}", WHITE, HAND_W)
    )
    items.append(("fill", circle_path(CX, CY, HUB_R), WHITE))
    return items


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def vector_xml(items, cap="round"):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tool/generate_app_icon.py. Do not edit by hand. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    android:width="108dp"',
        '    android:height="108dp"',
        '    android:viewportWidth="108"',
        '    android:viewportHeight="108">',
    ]
    for item in items:
        if item[0] == "stroke":
            _, d, colour, width = item
            lines += [
                "    <path",
                f'        android:pathData="{d}"',
                f'        android:strokeColor="{colour}"',
                f'        android:strokeWidth="{fmt(width)}"',
                f'        android:strokeLineCap="{cap}" />',
            ]
        else:
            _, d, colour = item
            lines += [
                "    <path",
                f'        android:pathData="{d}"',
                f'        android:fillColor="{colour}" />',
            ]
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def background_xml():
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_app_icon.py. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0 L108,0 L108,108 L0,108 Z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="0"
                android:endY="108"
                android:startColor="{BG_TOP}"
                android:endColor="{BG_BOTTOM}" />
        </aapt:attr>
    </path>
</vector>
"""


ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_app_icon.py. Do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""


def svg(items):
    parts = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="512" height="512">',
        "  <defs>",
        '    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">',
        f'      <stop offset="0" stop-color="{BG_TOP}"/>',
        f'      <stop offset="1" stop-color="{BG_BOTTOM}"/>',
        "    </linearGradient>",
        "  </defs>",
        '  <rect width="108" height="108" fill="url(#bg)"/>',
    ]
    for item in items:
        if item[0] == "stroke":
            _, d, colour, width = item
            parts.append(
                f'  <path d="{d}" fill="none" stroke="{colour}" '
                f'stroke-width="{fmt(width)}" stroke-linecap="round"/>'
            )
        else:
            _, d, colour = item
            parts.append(f'  <path d="{d}" fill="{colour}"/>')
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


# ---------------------------------------------------------------- raster


def hex_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))


def render(size, viewport=CANVAS, offset=0.0, mask="square", supersample=8):
    """Renders the icon. `viewport`/`offset` crop the 108 canvas."""
    big = size * supersample
    s = big / viewport

    def p(x, y):
        return ((x - offset) * s, (y - offset) * s)

    img = Image.new("RGBA", (big, big))
    top, bottom = hex_rgb(BG_TOP), hex_rgb(BG_BOTTOM)
    grad = Image.new("RGBA", (1, big))
    for y in range(big):
        t = ((y / s) + offset) / CANVAS
        grad.putpixel(
            (0, y), tuple(round(a + (b - a) * t) for a, b in zip(top, bottom)) + (255,)
        )
    img.paste(grad.resize((big, big)))
    d = ImageDraw.Draw(img)

    def cap(x, y, w, colour):
        rr = w / 2
        d.ellipse([*p(x - rr, y - rr), *p(x + rr, y + rr)], fill=colour)

    # PIL draws arc strokes inward from the box edge and measures angles
    # from 3 o'clock; shift both so the stroke is centred on the radius.
    def centred_arc(start, end, r, w, colour):
        box_r = r + w / 2
        box = [*p(CX - box_r, CY - box_r), *p(CX + box_r, CY + box_r)]
        d.arc(box, start - 90, end - 90, fill=colour, width=round(w * s))
        for a in (start, end):
            x, y = point(a, r)
            cap(x, y, w, colour)

    centred_arc(RING_START, RING_END, RING_R, RING_W, WHITE)
    d.polygon([p(*q) for q in arrow_points()], fill=WHITE)
    d.rounded_rectangle(
        [*p(CROWN[0], CROWN[1]), *p(CROWN[2], CROWN[3])],
        radius=CROWN_RADIUS * s,
        fill=WHITE,
    )
    d.rectangle([*p(STEM[0], STEM[1]), *p(STEM[2], STEM[3])], fill=WHITE)
    for st, en, c in step_arcs():
        centred_arc(st, en, STEP_R, STEP_W, c)
    hx, hy = hand_end()
    d.line([p(CX, CY), p(hx, hy)], fill=WHITE, width=round(HAND_W * s))
    cap(hx, hy, HAND_W, WHITE)
    d.ellipse([*p(CX - HUB_R, CY - HUB_R), *p(CX + HUB_R, CY + HUB_R)], fill=WHITE)

    alpha = Image.new("L", (big, big), 0)
    ad = ImageDraw.Draw(alpha)
    if mask == "circle":
        ad.ellipse([0, 0, big - 1, big - 1], fill=255)
    elif mask == "rounded":
        ad.rounded_rectangle([0, 0, big - 1, big - 1], radius=big * 0.2, fill=255)
    else:
        ad.rectangle([0, 0, big, big], fill=255)
    img.putalpha(alpha)
    return img.resize((size, size), Image.LANCZOS)


LEGACY_SIZES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def main():
    drawable = os.path.join(RES, "drawable")
    write(os.path.join(drawable, "ic_launcher_background.xml"), background_xml())
    write(os.path.join(drawable, "ic_launcher_foreground.xml"), vector_xml(shapes()))
    write(
        os.path.join(drawable, "ic_launcher_monochrome.xml"),
        vector_xml(shapes(monochrome=True)),
    )
    write(os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher.xml"), ADAPTIVE_XML)
    write(os.path.join(BRANDING, "app_icon.svg"), svg(shapes()))

    # Legacy icons show the 72 unit centre of the adaptive canvas.
    for density, size in LEGACY_SIZES.items():
        img = render(size, viewport=72, offset=18, mask="rounded")
        img.save(os.path.join(RES, f"mipmap-{density}", "ic_launcher.png"))
    render(512, viewport=78, offset=15, mask="square").save(
        os.path.join(BRANDING, "app_icon_512.png")
    )


if __name__ == "__main__":
    main()
